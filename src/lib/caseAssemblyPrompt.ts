import { remainingPlaceholdersIn, canSubmitTemplatePrompt, type TemplateCardJson } from "@/lib/templatePrompt";

export const CASE_PLACEHOLDERS = ["[ДИСЦИПЛИНА]", "[КУРС/ГОД ОБУЧЕНИЯ]", "[ТЕМА]", "[ЧЕМУ НАУЧИТЬСЯ]"] as const;

export const CASE_PLACEHOLDER_HINTS: Record<string, string> = {
  "[ДИСЦИПЛИНА]": "Ваша дисциплина или курс",
  "[КУРС/ГОД ОБУЧЕНИЯ]": "Например: «2 курс бакалавриата»",
  "[ТЕМА]": "Тема занятия, для которой нужен спорный кейс",
  "[ЧЕМУ НАУЧИТЬСЯ]": "Чему студенты должны научиться, разбирая этот кейс",
};

export const CASE_PROMPT_TEMPLATE = `Ты — методист, помогающий преподавателю собрать комплект материалов для дебатов и группового
обсуждения на занятии по методу «Сборка кейса».

Я преподаю [ДИСЦИПЛИНА] на [КУРС/ГОД ОБУЧЕНИЯ]. Хочу использовать реальное противоречие по
теме [ТЕМА], чтобы помочь студентам [ЧЕМУ НАУЧИТЬСЯ].

Собери для меня полный комплект в следующем порядке:

1. ПРОТИВОРЕЧИЯ. Предложи 5 возможных реальных противоречий (спорных вопросов) по этой теме,
которые можно использовать для кейса. Указывай источники и не выдумывай их. Из этих пяти
выбери самое сильное для дебатов и дальше работай только с ним.

2. ВВОДНЫЙ АБЗАЦ КЕЙСА. Напиши короткий вводный текст (не более 300 слов), который представит
выбранное противоречие как кейс. Текст должен объяснить суть противоречия и закончиться прямым
заданием для студентов: изучить материалы, выбрать сторону и обосновать выбор.

3. PRO-ХЕНДАУТ. Составь лист с 10 буллетами, поддерживающими позицию «за». Каждый буллет —
проверяемый факт, данные или результат исследования. Указывай источники и не выдумывай их.

4. CON-ХЕНДАУТ. Составь аналогичный список из 10 буллетов, но на этот раз — факты и данные,
поддерживающие позицию «против». Также указывай источники и не выдумывай их.

Формат ответа — Markdown, с явным заголовком перед каждым из четырёх пунктов выше.`;

export type CaseCardJson = TemplateCardJson;

export function remainingCasePlaceholders(text: string): string[] {
  return remainingPlaceholdersIn(text, CASE_PLACEHOLDERS);
}

export function canSubmitCasePrompt(card: CaseCardJson): boolean {
  return canSubmitTemplatePrompt(card, CASE_PLACEHOLDERS);
}
