import { remainingPlaceholdersIn, canSubmitTemplatePrompt, type TemplateCardJson } from "@/lib/templatePrompt";

export const PENTAGRAM_PLACEHOLDERS = ["[ДИСЦИПЛИНА]", "[УРОВЕНЬ СТУДЕНТОВ]"] as const;

export const PENTAGRAM_PLACEHOLDER_HINTS: Record<string, string> = {
  "[ДИСЦИПЛИНА]": "Ваша дисциплина или курс, под который нужны задания",
  "[УРОВЕНЬ СТУДЕНТОВ]": "Кто учится — школьники / бакалавриат / магистратура и т.п.",
};

export const PENTAGRAM_PROMPT_TEMPLATE = `[PERSONA] Ты — ведущий методист университета и эксперт по учебному дизайну, специализирующийся
на таксономии Блума и ИИ-резистентном оценивании. Твоя цель — помочь преподавателю
спроектировать задания, которые развивают глубокое мышление, а не просто проверяют
механическое выполнение работы.

[CONTEXT] Мы разрабатываем учебные задания для курса «[ДИСЦИПЛИНА]» для студентов
[УРОВЕНЬ СТУДЕНТОВ]. Студенты имеют неограниченный доступ к генеративному ИИ вне класса,
поэтому нам нужно чётко понимать, где ИИ является «лёгкой кнопкой» для списывания,
а где он стимулирует мышление.

[TASK] Разработай ровно по одному учебному заданию для каждого из 6 уровней обновлённой
таксономии Блума (Запоминание, Понимание, Применение, Анализ, Оценка, Создание). Для каждого
уровня: сформулируй задание через конкретный глагол Блума; опиши, что именно должен сделать
студент; оцени устойчивость (резистентность) этого задания к прямому списыванию через ИИ.

[OUTPUT] Представь ответ в виде Markdown-таблицы со следующими колонками: «Уровень Блума»,
«Глагол действия», «Описание задания для студента» и «ИИ-резистентность» (Низкая / Средняя /
Высокая). Пиши кратко, профессионально и ёмко.

[CONSTRAINT] Не используй размытые глаголы («понять», «изучить»). Никогда не предлагай
устаревшие инструменты (например, Flipgrid). Главное ограничение: задания уровней «Анализ»,
«Оценка» и «Создание» ДОЛЖНЫ быть спроектированы так, чтобы студент не мог просто скопировать
их в чат-бот и получить готовый ответ (например, через требования критического аудита
ИИ-выводов, работу с уникальным локальным контекстом или устную защиту).`;

export type PentagramCardJson = TemplateCardJson;

export function remainingPentagramPlaceholders(text: string): string[] {
  return remainingPlaceholdersIn(text, PENTAGRAM_PLACEHOLDERS);
}

export function canSubmitPentagramPrompt(card: PentagramCardJson): boolean {
  return canSubmitTemplatePrompt(card, PENTAGRAM_PLACEHOLDERS);
}
