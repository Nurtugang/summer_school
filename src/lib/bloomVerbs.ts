// Мягкая проверка: содержит ли поле "Результат обучения" глагол по Блуму
// (не блокирует отправку — только подсказка).
const BLOOM_VERB_STEMS = [
  "анализир",
  "проанализ",
  "спроектир",
  "проектир",
  "оцен",
  "созда",
  "разработа",
  "применит",
  "применя",
  "сравни",
  "сопостав",
  "классифиц",
  "интерпретир",
  "спрогнозир",
  "диагностир",
  "аргументир",
  "обоснова",
  "синтезир",
  "критик",
  "решит",
  "решени",
  "спланир",
  "сконструир",
];

export function containsBloomVerb(text: string): boolean {
  const lower = text.toLowerCase();
  return BLOOM_VERB_STEMS.some((stem) => lower.includes(stem));
}
